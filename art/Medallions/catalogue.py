#!/usr/bin/env python3
"""Medallion catalogue: Catalogue.md (a table of every design) and Catalogue.png (a contact sheet).

Reads each design folder's build_info.json (written by image_to_3mf.py) and preview PNG. The
numbering is kept in catalogue.json: every design keeps its M-number, new folders get the next
free numbers (in alphabetical order), and a removed design's number is retired, not reused.
image_to_3mf.py runs this after every build; run it by hand after renaming or removing a folder.

usage:
  python catalogue.py
"""
import json, os
from urllib.parse import quote

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = os.path.join(HERE, 'catalogue.json')
COLS, CELL, PAD = 5, 420, 24                     # contact sheet: columns, preview box px, margin
CARD_H = CELL + 150


def designs():
    """[(number, folder, info)] by number; updates catalogue.json.

    catalogue.json maps each design to its M-number. A removed design's number is retired (listed
    under "retired") and never reused; new folders get the next number after the highest ever given."""
    found = sorted(d for d in os.listdir(HERE) if os.path.isfile(os.path.join(HERE, d, 'build_info.json')))
    data = json.load(open(ORDER, encoding='utf-8')) if os.path.isfile(ORDER) else {}
    if 'order' in data:                            # older layout: a plain list, numbered 1..n
        data = {'numbers': {d: i for i, d in enumerate(data['order'], 1)}}
    numbers, retired = data.get('numbers', {}), data.get('retired', {})
    for d in [d for d in numbers if d not in found]:
        retired[d] = numbers.pop(d)
    top = max(list(numbers.values()) + list(retired.values()) + [0])
    for d in found:
        if d not in numbers:
            top += 1
            numbers[d] = top
    numbers = dict(sorted(numbers.items(), key=lambda kv: kv[1]))
    retired = dict(sorted(retired.items(), key=lambda kv: kv[1]))
    with open(ORDER, 'w', encoding='utf-8') as f:
        json.dump({'numbers': numbers, 'retired': retired}, f, indent=2)
        f.write('\n')
    return [(n, d, json.load(open(os.path.join(HERE, d, 'build_info.json'), encoding='utf-8')))
            for d, n in numbers.items()]


def preview(folder):
    return os.path.join(folder, folder.replace(' ', '_') + '.png')


def hang_hole(info):
    if not info['holes']:
        return 'none'
    w, h = max(info['holes'], key=lambda s: s[0] * s[1])
    return f'{w:.1f} mm' if abs(w - h) < 0.3 else f'{w:.1f} × {h:.1f} mm'


def write_md(items):
    rows = []
    for n, d, info in items:
        img = quote(preview(d).replace(os.sep, '/'))
        w, h = info['size']
        cols = ', '.join(c for c, _ in info['colours'])
        time = info['print_time'] or 'not sliced'
        grams = f"{info['filament_g']:.0f} g" if info['filament_g'] else '–'
        rows.append(f'| M{n:02d} | <img src="{img}" width="140"> | [{d}]({quote(d)}/) | '
                    f'{w:.1f} × {h:.1f} | {len(info["colours"])}: {cols} | {hang_hole(info)} | {time} | {grams} |')
    md = ['# Medallion Catalogue', '',
          f'{len(items)} designs. Each is {items[0][2]["thickness"]:.1f} mm thick: '
          f'colour on both faces around a single-colour core (the first colour listed), '
          f'printed in Bambu PLA Basic on the {items[0][2]["printer"]}. Print time and filament '
          '(including purge) are from slicing each project in Bambu Studio at 35 % infill.', '',
          'This file and [Catalogue.png](Catalogue.png) are generated by `catalogue.py` from each '
          "folder's `build_info.json`; `image_to_3mf.py` refreshes them after every build. "
          'See [README.md](README.md) for how to add a design.', '',
          '| # | Preview | Design | Size (mm) | Colours | Hang hole | Print time | Filament |',
          '|---|---|---|---|---|---|---|---|'] + rows + ['']
    with open(os.path.join(HERE, 'Catalogue.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(md))


def font(size, bold=False):
    for name in (('arialbd.ttf', 'DejaVuSans-Bold.ttf') if bold else ('arial.ttf', 'DejaVuSans.ttf')):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            pass
    return ImageFont.load_default(size)


def write_png(items):
    rows = (len(items) + COLS - 1) // COLS
    W = PAD + COLS * (CELL + PAD)
    head = 110
    sheet = Image.new('RGB', (W, head + rows * (CARD_H + PAD) + PAD), '#EDEBE6')
    dr = ImageDraw.Draw(sheet)
    dr.text((PAD, 28), 'Medallion Catalogue', font=font(48, True), fill='#222222')
    dr.text((W - PAD, 46), f'{len(items)} designs · Bambu PLA Basic', font=font(26), fill='#555555', anchor='ra')
    f_name, f_small = font(24, True), font(20)
    for k, (n, d, info) in enumerate(items):
        x = PAD + (k % COLS) * (CELL + PAD)
        y = head + (k // COLS) * (CARD_H + PAD)
        dr.rounded_rectangle((x, y, x + CELL, y + CARD_H), 16, fill='#FFFFFF', outline='#D6D3CC')
        im = Image.open(os.path.join(HERE, preview(d))).convert('RGBA')
        im.thumbnail((CELL - 40, CELL - 40), Image.LANCZOS)
        # light backing so white parts of the medallion read against the white card
        bg = Image.new('RGBA', (CELL - 20, CELL - 20), '#E4E2DC')
        bg.alpha_composite(im, ((bg.width - im.width) // 2, (bg.height - im.height) // 2))
        sheet.paste(bg.convert('RGB'), (x + 10, y + 10))
        ty = y + CELL + 4
        dr.text((x + 14, ty), f'M{n:02d}  {d.replace(" Medallion", "")}', font=f_name, fill='#222222')
        w, h = info['size']
        meta = f'{w:.0f} × {h:.0f} mm · {info["print_time"] or "not sliced"}'
        if info['filament_g']:
            meta += f' · {info["filament_g"]:.0f} g'
        dr.text((x + 14, ty + 36), meta, font=f_small, fill='#555555')
        cx = x + 14
        step = min(38, (CELL - 28 - 30) / max(1, len(info['colours']) - 1))
        for _, hexc in info['colours']:              # filament chips, squeezed to fit the card
            dr.ellipse((cx, ty + 74, cx + 30, ty + 104), fill=hexc, outline='#888888')
            cx += step
    sheet.save(os.path.join(HERE, 'Catalogue.png'), optimize=True)


def main():
    items = designs()
    if not items:
        print('catalogue: no built designs (build_info.json) found')
        return
    write_md(items)
    write_png(items)
    print(f'catalogue: {len(items)} designs -> Catalogue.md, Catalogue.png')


if __name__ == '__main__':
    main()
